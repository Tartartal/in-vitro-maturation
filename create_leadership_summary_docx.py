def build_document_xml() -> str:
    parts = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">',
        "<w:body>",
        p_center(TITLE, bold=True, size=32),
        p_center(ARTICLE, bold=True, size=26),
        p_center(SUBTITLE, italic=True, size=24),
    ]
    for heading, paras in SECTIONS:
        parts.append(p_heading(heading))
        for para in paras:
            parts.append(p(para))
    parts.append(p_heading("Источник"))
    for src in SOURCES:
        parts.append(p_source(src))
    parts.append(
        "<w:sectPr>"
        '<w:pgSz w:w="11906" w:h="16838"/>'
        '<w:pgMar w:top="1418" w:right="1418" w:bottom="1418" w:left="1418" '
        'w:header="708" w:footer="708" w:gutter="0"/>'
        "</w:sectPr>"
    )
    parts.append("</w:body></w:document>")
    return "".join(parts)


def main() -> None:
    with zipfile.ZipFile(OUT, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", CONTENT_TYPES)
        zf.writestr("_rels/.rels", RELS)
        zf.writestr("word/_rels/document.xml.rels", DOC_RELS)
        zf.writestr("word/styles.xml", STYLES)
        zf.writestr("word/document.xml", build_document_xml())
    print(f"Created: {OUT}")


if __name__ == "__main__":
    main()
